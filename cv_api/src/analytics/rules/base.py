"""Shared types and interfaces for modular analytics rules."""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
from typing import TYPE_CHECKING, Any

from src.analytics.schemas import VisionEvent
from src.analytics.tracker import TrackedObject

if TYPE_CHECKING:
    from src.analytics.rules.engine import Line, Zone, ZoneRuleEngine

Point = tuple[float, float]


@dataclass
class Rule:
    """A configured rule type and its optional parameters."""

    type: str
    params: dict[str, Any] = field(default_factory=dict)


@dataclass
class _TrackState:
    """Historical information shared by handlers for one tracked object."""

    zones_inside: set[str] = field(default_factory=set)
    zone_entry_time: dict[str, float] = field(default_factory=dict)
    dwell_fired: set[str] = field(default_factory=set)
    last_point: Point | None = None


class RuleHandler:
    """Interface implemented by one analytics rule."""

    def evaluate_zone(
        self,
        _engine: ZoneRuleEngine,
        _camera_id: str,
        _obj: TrackedObject,
        _zone: Zone,
        _rule: Rule,
        _state: _TrackState,
        _timestamp: datetime,
        _is_inside: bool,
        _was_inside: bool,
    ) -> list[VisionEvent]:
        """Return events generated by a polygon-zone evaluation."""
        return []

    def evaluate_line(
        self,
        _engine: ZoneRuleEngine,
        _camera_id: str,
        _obj: TrackedObject,
        _line: Line,
        _rule: Rule,
        _state: _TrackState,
        _timestamp: datetime,
        _crossed: bool,
        *_points: Point,
    ) -> list[VisionEvent]:
        """Return events generated by a line evaluation."""
        return []


def rule_applies_to_object(rule: Rule, obj: TrackedObject) -> bool:
    """Apply configured object classes, defaulting to people."""
    classes = rule.params.get("object_classes", rule.params.get("classes"))
    if classes is None:
        return obj.class_name == "person"
    if isinstance(classes, str):
        classes = [classes]
    return obj.class_name in classes
